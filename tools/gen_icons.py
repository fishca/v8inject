#!/usr/bin/env python3
"""Regenerate src/payload/icons.h from the PNGs in src/payload/icons/.

The GitBar glyphs are 1C's own toolbar pictures (see icons/SOURCE.json), so the
panel looks like part of the configurator. GDI has no alpha blending of its own
and the payload must not pull in GDI+ just to decode a PNG, so the images are
baked here into 16x16 premultiplied BGRA arrays (what AlphaBlend wants).

Run from the repo root:  python tools/gen_icons.py
"""
import json
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ICON_DIR = os.path.join(ROOT, "src", "payload", "icons")
OUT = os.path.join(ROOT, "src", "payload", "icons.h")

ROLES = [
    ("dump", "kIconDump"),
    ("init", "kIconInit"),
    ("commit", "kIconCommit"),
    ("push", "kIconPush"),
    ("settings", "kIconSettings"),
]


def paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def decode_png(blob):
    assert blob[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    i = 8
    idat = b""
    w = h = bitdepth = colortype = None
    while i < len(blob):
        ln = struct.unpack(">I", blob[i:i + 4])[0]
        typ = blob[i + 4:i + 8]
        body = blob[i + 8:i + 8 + ln]
        if typ == b"IHDR":
            w, h, bitdepth, colortype = struct.unpack(">IIBB", body[:10])
            assert bitdepth == 8, f"bit depth {bitdepth} not supported"
            assert colortype == 6, f"color type {colortype} not supported (need RGBA)"
        elif typ == b"IDAT":
            idat += body
        elif typ == b"IEND":
            break
        i += 12 + ln

    raw = zlib.decompress(idat)
    bpp = 4
    stride = w * bpp
    out = bytearray(h * stride)
    prev = bytearray(stride)
    pos = 0
    for y in range(h):
        f = raw[pos]
        pos += 1
        line = bytearray(raw[pos:pos + stride])
        pos += stride
        if f == 1:      # Sub
            for x in range(bpp, stride):
                line[x] = (line[x] + line[x - bpp]) & 0xFF
        elif f == 2:    # Up
            for x in range(stride):
                line[x] = (line[x] + prev[x]) & 0xFF
        elif f == 3:    # Average
            for x in range(stride):
                left = line[x - bpp] if x >= bpp else 0
                line[x] = (line[x] + ((left + prev[x]) >> 1)) & 0xFF
        elif f == 4:    # Paeth
            for x in range(stride):
                left = line[x - bpp] if x >= bpp else 0
                upleft = prev[x - bpp] if x >= bpp else 0
                line[x] = (line[x] + paeth(left, prev[x], upleft)) & 0xFF
        elif f != 0:
            raise ValueError(f"bad filter {f}")
        out[y * stride:(y + 1) * stride] = line
        prev = line
    return w, h, out


def premultiplied_bgra(w, h, rgba):
    px = bytearray(w * h * 4)
    for i in range(w * h):
        r, g, b, a = rgba[i * 4:i * 4 + 4]
        # AlphaBlend with AC_SRC_ALPHA expects premultiplied colour.
        px[i * 4 + 0] = (b * a + 127) // 255
        px[i * 4 + 1] = (g * a + 127) // 255
        px[i * 4 + 2] = (r * a + 127) // 255
        px[i * 4 + 3] = a
    return px


def main():
    lines = [
        "// Generated by tools/gen_icons.py - do not edit by hand.",
        "// 1C's own toolbar pictures (16x16, premultiplied BGRA for AlphaBlend);",
        "// sources are the PNGs next to this header, see icons/SOURCE.json.",
        "#pragma once",
        "",
        "namespace v8i {",
        "namespace icons {",
        "",
        "const int kSize = 16;",
        "",
    ]
    for role, cname in ROLES:
        path = os.path.join(ICON_DIR, role + ".png")
        w, h, rgba = decode_png(open(path, "rb").read())
        if (w, h) != (16, 16):
            sys.exit(f"{role}.png is {w}x{h}, expected 16x16")
        px = premultiplied_bgra(w, h, rgba)
        lines.append(f"// {role}.png")
        lines.append(f"const unsigned char {cname}[{len(px)}] = {{")
        for off in range(0, len(px), 16):
            row = ", ".join(f"0x{b:02X}" for b in px[off:off + 16])
            lines.append("    " + row + ",")
        lines.append("};")
        lines.append("")
    lines += ["}  // namespace icons", "}  // namespace v8i", ""]
    open(OUT, "w", newline="\n").write("\n".join(lines))
    print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes)")


if __name__ == "__main__":
    main()
