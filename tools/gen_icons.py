#!/usr/bin/env python3
"""Regenerate src/payload/icons.h and src/payload/icons_png.h from the PNGs
in src/payload/icons/.

The GitBar glyphs are original artwork drawn by tools/draw_icons.py in the
Configurator's palette (beige/blue/green/gold, 16x16, beveled "plastic" look);
they are not extracted from 1C's resource bundles, see icons/SOURCE.json.

GDI has no alpha blending of its own and the payload must not pull in GDI+
just to decode a PNG, so the images are baked here into 16x16 premultiplied
BGRA arrays (what AlphaBlend wants). The raw PNG bytes go to a second header:
the native main-menu item can only point the platform at a picture URL.

Run from the repo root:  python tools/gen_icons.py
"""
import json
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ICON_DIR = os.path.join(ROOT, "src", "payload", "icons")
OUT = os.path.join(ROOT, "src", "payload", "icons.h")
OUT_PNG = os.path.join(ROOT, "src", "payload", "icons_png.h")

ROLES = [
    ("dump", "kIconDump"),
    ("dumpext", "kIconDumpExt"),
    ("init", "kIconInit"),
    ("clone", "kIconClone"),
    ("commit", "kIconCommit"),
    ("push", "kIconPush"),
    ("pull", "kIconPull"),
    ("fetch", "kIconFetch"),
    ("branches", "kIconBranches"),
    ("stash", "kIconStash"),
    ("tags", "kIconTags"),
    ("status", "kIconStatus"),
    ("log", "kIconLog"),
    ("settings", "kIconSettings"),
    ("gitbar", "kIconGitBar"),
]


def paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def decode_png(blob):
    assert blob[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    i = 8
    idat = b""
    w = h = bitdepth = colortype = None
    while i < len(blob):
        ln = struct.unpack(">I", blob[i:i + 4])[0]
        typ = blob[i + 4:i + 8]
        body = blob[i + 8:i + 8 + ln]
        if typ == b"IHDR":
            w, h, bitdepth, colortype = struct.unpack(">IIBB", body[:10])
            assert bitdepth == 8, f"bit depth {bitdepth} not supported"
            assert colortype == 6, f"color type {colortype} not supported (need RGBA)"
        elif typ == b"IDAT":
            idat += body
        elif typ == b"IEND":
            break
        i += 12 + ln

    raw = zlib.decompress(idat)
    bpp = 4
    stride = w * bpp
    out = bytearray(h * stride)
    prev = bytearray(stride)
    pos = 0
    for y in range(h):
        f = raw[pos]
        pos += 1
        line = bytearray(raw[pos:pos + stride])
        pos += stride
        if f == 1:      # Sub
            for x in range(bpp, stride):
                line[x] = (line[x] + line[x - bpp]) & 0xFF
        elif f == 2:    # Up
            for x in range(stride):
                line[x] = (line[x] + prev[x]) & 0xFF
        elif f == 3:    # Average
            for x in range(stride):
                left = line[x - bpp] if x >= bpp else 0
                line[x] = (line[x] + ((left + prev[x]) >> 1)) & 0xFF
        elif f == 4:    # Paeth
            for x in range(stride):
                left = line[x - bpp] if x >= bpp else 0
                upleft = prev[x - bpp] if x >= bpp else 0
                line[x] = (line[x] + paeth(left, prev[x], upleft)) & 0xFF
        elif f != 0:
            raise ValueError(f"bad filter {f}")
        out[y * stride:(y + 1) * stride] = line
        prev = line
    return w, h, out


def premultiplied_bgra(w, h, rgba):
    px = bytearray(w * h * 4)
    for i in range(w * h):
        r, g, b, a = rgba[i * 4:i * 4 + 4]
        # AlphaBlend with AC_SRC_ALPHA expects premultiplied colour.
        px[i * 4 + 0] = (b * a + 127) // 255
        px[i * 4 + 1] = (g * a + 127) // 255
        px[i * 4 + 2] = (r * a + 127) // 255
        px[i * 4 + 3] = a
    return px


def main():
    lines = [
        "// Generated by tools/gen_icons.py - do not edit by hand.",
        "// Original 16x16 GitBar glyphs (tools/draw_icons.py) in the Configurator's",
        "// palette, baked to premultiplied BGRA for AlphaBlend; sources are the",
        "// PNGs next to this header, see icons/SOURCE.json.",
        "#pragma once",
        "",
        "namespace v8i {",
        "namespace icons {",
        "",
        "const int kSize = 16;",
        "",
    ]
    for role, cname in ROLES:
        path = os.path.join(ICON_DIR, role + ".png")
        w, h, rgba = decode_png(open(path, "rb").read())
        if (w, h) != (16, 16):
            sys.exit(f"{role}.png is {w}x{h}, expected 16x16")
        px = premultiplied_bgra(w, h, rgba)
        lines.append(f"// {role}.png")
        lines.append(f"const unsigned char {cname}[{len(px)}] = {{")
        for off in range(0, len(px), 16):
            row = ", ".join(f"0x{b:02X}" for b in px[off:off + 16])
            lines.append("    " + row + ",")
        lines.append("};")
        lines.append("")
    lines += ["}  // namespace icons", "}  // namespace v8i", ""]
    open(OUT, "w", newline="\n").write("\n".join(lines))
    print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes)")

    # The native main-menu item has no toolbar code path: it can only point at a
    # picture through a URL, so the payload writes these PNGs to the temp dir and
    # references them as file:// URLs (see src/payload/mainmenu.cpp). The bytes
    # are the platform's own pictures, so the menu looks exactly like the strip.
    png_lines = [
        "// Generated by tools/gen_icons.py - do not edit by hand.",
        "// Raw PNG bytes of the original GitBar glyphs (tools/draw_icons.py): the",
        "// native menu item points the platform at a file:// copy of these files,",
        "// so the menu draws the same pictures as the toolbar strip.",
        "#pragma once",
        "",
        "namespace v8i {",
        "namespace icons {",
        "",
        "struct PngResource {",
        "    const char* name;",
        "    const unsigned char* data;",
        "    unsigned size;",
        "};",
        "",
    ]
    table = []
    for role, _cname in ROLES:
        blob = open(os.path.join(ICON_DIR, role + ".png"), "rb").read()
        var = "kPng" + role.capitalize()
        png_lines.append(f"// {role}.png ({len(blob)} bytes)")
        png_lines.append(f"inline const unsigned char {var}[{len(blob)}] = {{")
        for off in range(0, len(blob), 16):
            row = ", ".join(f"0x{b:02X}" for b in blob[off:off + 16])
            png_lines.append("    " + row + ",")
        png_lines.append("};")
        png_lines.append("")
        table.append(f'    {{"{role}", {var}, sizeof({var})}},')
    png_lines += [
        "inline const PngResource kPngs[] = {",
        *table,
        "};",
        "inline const int kPngCount =",
        "    sizeof(kPngs) / sizeof(kPngs[0]);",
        "",
        "}  // namespace icons",
        "}  // namespace v8i",
        "",
    ]
    open(OUT_PNG, "w", newline="\n").write("\n".join(png_lines))
    print(f"wrote {OUT_PNG} ({os.path.getsize(OUT_PNG)} bytes)")


if __name__ == "__main__":
    main()
